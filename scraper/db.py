"""
db.py — Database layer for News Pulse.

Supports:
  - SQLite (default, zero-config local dev)
  - PostgreSQL via DATABASE_URL env var (Neon / Supabase for production)

Tables:
  articles  — raw ingested articles (deduplicated by URL hash)
  clusters  — topic clusters generated by the clustering step
  cluster_articles — many-to-many link between articles and clusters
"""

import hashlib
import logging
import sqlite3
from datetime import datetime, timezone
from contextlib import contextmanager

try:
    import psycopg
    import psycopg.rows
    PSYCOPG2_AVAILABLE = True
except ImportError:
    PSYCOPG2_AVAILABLE = False

from config import DATABASE_URL, SQLITE_PATH

log = logging.getLogger(__name__)

# ─── DDL ──────────────────────────────────────────────────────────────────────

SCHEMA_SQL = """
CREATE TABLE IF NOT EXISTS articles (
    id           INTEGER PRIMARY KEY AUTOINCREMENT,
    url_hash     TEXT UNIQUE NOT NULL,
    url          TEXT NOT NULL,
    headline     TEXT,
    summary      TEXT,
    body         TEXT,
    source_id    TEXT,
    source_name  TEXT,
    published_at TEXT,
    fetched_at   TEXT NOT NULL,
    scrape_ok    INTEGER DEFAULT 0
);

CREATE TABLE IF NOT EXISTS clusters (
    id           INTEGER PRIMARY KEY AUTOINCREMENT,
    label        TEXT NOT NULL,
    keywords     TEXT,
    article_count INTEGER DEFAULT 0,
    earliest_at  TEXT,
    latest_at    TEXT,
    created_at   TEXT NOT NULL
);

CREATE TABLE IF NOT EXISTS cluster_articles (
    cluster_id   INTEGER NOT NULL REFERENCES clusters(id) ON DELETE CASCADE,
    article_id   INTEGER NOT NULL REFERENCES articles(id) ON DELETE CASCADE,
    PRIMARY KEY (cluster_id, article_id)
);
"""

# PostgreSQL-compatible DDL (SERIAL vs AUTOINCREMENT)
SCHEMA_SQL_PG = """
CREATE TABLE IF NOT EXISTS articles (
    id           SERIAL PRIMARY KEY,
    url_hash     TEXT UNIQUE NOT NULL,
    url          TEXT NOT NULL,
    headline     TEXT,
    summary      TEXT,
    body         TEXT,
    source_id    TEXT,
    source_name  TEXT,
    published_at TEXT,
    fetched_at   TEXT NOT NULL,
    scrape_ok    BOOLEAN DEFAULT FALSE
);

CREATE TABLE IF NOT EXISTS clusters (
    id           SERIAL PRIMARY KEY,
    label        TEXT NOT NULL,
    keywords     TEXT,
    article_count INTEGER DEFAULT 0,
    earliest_at  TEXT,
    latest_at    TEXT,
    created_at   TEXT NOT NULL
);

CREATE TABLE IF NOT EXISTS cluster_articles (
    cluster_id   INTEGER NOT NULL REFERENCES clusters(id) ON DELETE CASCADE,
    article_id   INTEGER NOT NULL REFERENCES articles(id) ON DELETE CASCADE,
    PRIMARY KEY (cluster_id, article_id)
);
"""

# ─── Backend Detection ─────────────────────────────────────────────────────────

def _use_postgres() -> bool:
    return bool(DATABASE_URL) and PSYCOPG2_AVAILABLE


# ─── SQLite helpers ────────────────────────────────────────────────────────────

@contextmanager
def _sqlite_conn():
    conn = sqlite3.connect(SQLITE_PATH)
    conn.row_factory = sqlite3.Row
    conn.execute("PRAGMA journal_mode=WAL")
    try:
        yield conn
        conn.commit()
    except Exception:
        conn.rollback()
        raise
    finally:
        conn.close()


# ─── PostgreSQL helpers ────────────────────────────────────────────────────────

@contextmanager
def _pg_conn():
    conn = psycopg.connect(DATABASE_URL)
    conn.autocommit = False
    try:
        yield conn
        conn.commit()
    except Exception:
        conn.rollback()
        raise
    finally:
        conn.close()


# ─── Public API ────────────────────────────────────────────────────────────────

def init_db():
    """Create all tables if they do not exist."""
    if _use_postgres():
        log.info("Using PostgreSQL database")
        with _pg_conn() as conn:
            with conn.cursor() as cur:
                cur.execute(SCHEMA_SQL_PG)
    else:
        log.info(f"Using SQLite database: {SQLITE_PATH}")
        with _sqlite_conn() as conn:
            conn.executescript(SCHEMA_SQL)
    log.info("Database initialized successfully")


def url_hash(url: str) -> str:
    """Deterministic SHA-256 hash of a URL for deduplication."""
    return hashlib.sha256(url.strip().lower().encode()).hexdigest()


def save_articles(articles: list[dict]) -> list[int]:
    """
    Upsert articles into the DB. Skips duplicates by url_hash.
    Returns list of newly inserted article IDs.
    """
    now = datetime.now(timezone.utc).isoformat()
    inserted_ids = []

    if _use_postgres():
        with _pg_conn() as conn:
            with conn.cursor() as cur:
                for art in articles:
                    h = url_hash(art["url"])
                    cur.execute(
                        """
                        INSERT INTO articles
                            (url_hash, url, headline, summary, body,
                             source_id, source_name, published_at,
                             fetched_at, scrape_ok)
                        VALUES (%s,%s,%s,%s,%s,%s,%s,%s,%s,%s)
                        ON CONFLICT (url_hash) DO NOTHING
                        RETURNING id
                        """,
                        (
                            h, art["url"], art.get("headline"),
                            art.get("summary"), art.get("body"),
                            art.get("source_id"), art.get("source_name"),
                            art.get("published_at"), now,
                            bool(art.get("scrape_ok", False)),
                        ),
                    )
                    row = cur.fetchone()
                    if row:
                        inserted_ids.append(row[0])
    else:
        with _sqlite_conn() as conn:
            for art in articles:
                h = url_hash(art["url"])
                try:
                    cur = conn.execute(
                        """
                        INSERT OR IGNORE INTO articles
                            (url_hash, url, headline, summary, body,
                             source_id, source_name, published_at,
                             fetched_at, scrape_ok)
                        VALUES (?,?,?,?,?,?,?,?,?,?)
                        """,
                        (
                            h, art["url"], art.get("headline"),
                            art.get("summary"), art.get("body"),
                            art.get("source_id"), art.get("source_name"),
                            art.get("published_at"), now,
                            1 if art.get("scrape_ok") else 0,
                        ),
                    )
                    if cur.lastrowid:
                        inserted_ids.append(cur.lastrowid)
                except Exception as e:
                    log.warning(f"Failed to insert article {art.get('url')}: {e}")

    log.info(f"Saved {len(inserted_ids)} new articles (skipped duplicates)")
    return inserted_ids


def get_recent_articles(limit: int = 300) -> list[dict]:
    """
    Fetch the most recent articles for clustering.
    Returns list of dicts with id, headline, summary, body, source_id etc.
    """
    sql = """
        SELECT id, url, headline, summary, body, source_id, source_name,
               published_at, fetched_at, scrape_ok
        FROM articles
        ORDER BY fetched_at DESC
        LIMIT ?
    """
    if _use_postgres():
        sql = sql.replace("?", "%s")
        with _pg_conn() as conn:
            with conn.cursor(row_factory=psycopg.rows.dict_row) as cur:
                cur.execute(sql, (limit,))
                return [dict(r) for r in cur.fetchall()]
    else:
        with _sqlite_conn() as conn:
            rows = conn.execute(sql, (limit,)).fetchall()
            return [dict(r) for r in rows]


def get_articles_by_ids(article_ids: list[int]) -> list[dict]:
    """Fetch newly inserted articles by ID so only new items are enriched."""
    if not article_ids:
        return []
    placeholders = ",".join("%s" if _use_postgres() else "?" for _ in article_ids)
    sql = f"""
        SELECT id, url, headline, summary, body, source_id, source_name,
               published_at, fetched_at, scrape_ok
        FROM articles WHERE id IN ({placeholders})
    """
    if _use_postgres():
        with _pg_conn() as conn:
            with conn.cursor(row_factory=psycopg.rows.dict_row) as cur:
                cur.execute(sql, article_ids)
                return [dict(row) for row in cur.fetchall()]
    with _sqlite_conn() as conn:
        rows = conn.execute(sql, article_ids).fetchall()
        return [dict(row) for row in rows]


def save_clusters(clusters: list[dict]):
    """
    Persist cluster results to DB.
    Each cluster dict must have: label, keywords, article_ids (list), earliest_at, latest_at
    Clears old clusters before inserting fresh ones.
    """
    now = datetime.now(timezone.utc).isoformat()

    if _use_postgres():
        with _pg_conn() as conn:
            with conn.cursor() as cur:
                cur.execute("DELETE FROM cluster_articles")
                cur.execute("DELETE FROM clusters")
                for cl in clusters:
                    cur.execute(
                        """
                        INSERT INTO clusters
                            (label, keywords, article_count, earliest_at, latest_at, created_at)
                        VALUES (%s,%s,%s,%s,%s,%s) RETURNING id
                        """,
                        (
                            cl["label"],
                            ",".join(cl.get("keywords", [])),
                            len(cl.get("article_ids", [])),
                            cl.get("earliest_at"),
                            cl.get("latest_at"),
                            now,
                        ),
                    )
                    cluster_id = cur.fetchone()[0]
                    for art_id in cl.get("article_ids", []):
                        cur.execute(
                            "INSERT INTO cluster_articles (cluster_id, article_id) VALUES (%s,%s)",
                            (cluster_id, art_id),
                        )
    else:
        with _sqlite_conn() as conn:
            conn.execute("DELETE FROM cluster_articles")
            conn.execute("DELETE FROM clusters")
            for cl in clusters:
                cur = conn.execute(
                    """
                    INSERT INTO clusters
                        (label, keywords, article_count, earliest_at, latest_at, created_at)
                    VALUES (?,?,?,?,?,?)
                    """,
                    (
                        cl["label"],
                        ",".join(cl.get("keywords", [])),
                        len(cl.get("article_ids", [])),
                        cl.get("earliest_at"),
                        cl.get("latest_at"),
                        now,
                    ),
                )
                cluster_id = cur.lastrowid
                conn.executemany(
                    "INSERT INTO cluster_articles (cluster_id, article_id) VALUES (?,?)",
                    [(cluster_id, aid) for aid in cl.get("article_ids", [])],
                )

    log.info(f"Saved {len(clusters)} clusters to database")


def update_article_bodies(articles: list[dict]):
    """
    UPDATE body text and scrape_ok status for articles that were enriched.
    Matches by url_hash so we never create duplicates.
    """
    updates = [
        (art.get("body"), 1 if art.get("scrape_ok") else 0, url_hash(art["url"]))
        for art in articles
        if art.get("url") and art.get("scrape_ok")
    ]
    if not updates:
        log.info("No article bodies to update")
        return

    if _use_postgres():
        with _pg_conn() as conn:
            with conn.cursor() as cur:
                for body, ok, h in updates:
                    cur.execute(
                        "UPDATE articles SET body=%s, scrape_ok=%s WHERE url_hash=%s",
                        (body, bool(ok), h),
                    )
    else:
        with _sqlite_conn() as conn:
            conn.executemany(
                "UPDATE articles SET body=?, scrape_ok=? WHERE url_hash=?",
                updates,
            )

    log.info(f"Updated body text for {len(updates)} articles in database")

